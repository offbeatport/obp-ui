// Split the monolithic design prototype into one standalone HTML page per feature, so each
// feature can be referenced in isolation (file://…/split/<feature>.html) instead of scrolling
// a 12k-line file. Each page is a STATIC snapshot: the prototype is rendered to that feature's
// state in a headless browser, then its <script> tags are stripped so opening the file shows a
// frozen, faithful view (full CSS kept). Interactivity is intentionally gone — these are for
// reading/pointing at, not using.
//
//   node scripts/split-prototype.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const SRC = resolve(root, "design/v2-prototypes/08-chat-spine-pro-v7.html");
const OUT = resolve(root, "design/v2-prototypes/split");
mkdirSync(OUT, { recursive: true });

// feature → the prototype JS that navigates to it (all fns are globals in the inline script).
const FEATURES = [
    { name: "home", title: "Home dashboard", js: "applyDemo('full'); setNav('dash1');" },
    { name: "spin-1-composer", title: "Start a company · composer", js: "renderSpin('composer');" },
    { name: "spin-2-scouting", title: "Start a company · scouting", js: "renderSpin('scouting');" },
    { name: "spin-3-proposals", title: "Start a company · proposals", js: "renderSpin('proposals');" },
    { name: "spin-4-spec", title: "Start a company · spec + branding", js: "renderSpin('composer'); spinChooseAngle(1);" },
    { name: "company", title: "Company workspace", js: "applyDemo('full'); zoom('leadsift');" },
    { name: "inbox", title: "Inbox / needs-you", js: "setNav('needs');" },
    { name: "opportunities", title: "Opportunities", js: "setNav('opportunities');" },
    { name: "all-companies", title: "All companies", js: "setNav('allco');" },
    { name: "manage", title: "Manage", js: "setNav('manage');" },
    { name: "money", title: "Manage · money", js: "setNav('money');" },
    { name: "autonomy", title: "Manage · autonomy", js: "setNav('autonomy');" },
    { name: "oversight", title: "Manage · oversight", js: "setNav('oversight');" },
];

// Strip <script> blocks so the saved page is a static snapshot (won't re-run to the default view).
function freeze(html, title) {
    const stripped = html.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, "");
    const banner = `<!-- STATIC SNAPSHOT · ${title} · generated from 08-chat-spine-pro-v7.html by scripts/split-prototype.mjs. Do not edit; regenerate. -->\n`;
    return banner + stripped;
}

const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 960 } });
const page = await ctx.newPage();
page.on("pageerror", () => {}); // ignore prototype console noise
await page.goto(`file://${SRC}`, { waitUntil: "load", timeout: 30000 });
await page.waitForTimeout(600);

const done = [];
for (const f of FEATURES) {
    try {
        await page.evaluate((code) => {
            // biome-ignore lint: prototype globals evaluated in page context
            new Function(code)();
        }, f.js);
        await page.waitForTimeout(450);
        const html = await page.content();
        const file = resolve(OUT, `${f.name}.html`);
        writeFileSync(file, freeze(html, f.title));
        done.push(f);
        console.log("✓", f.name);
    } catch (e) {
        console.warn("✗", f.name, "-", e.message);
    }
}
await browser.close();

// index.html linking every snapshot + a README mapping features → files.
const links = done
    .map((f) => `    <li><a href="./${f.name}.html">${f.title}</a> <code>${f.name}.html</code></li>`)
    .join("\n");
const src = readFileSync(SRC, "utf8");
const indexHtml = `<!doctype html><meta charset="utf-8"><title>Prototype · split by feature</title>
<style>body{font:15px/1.6 system-ui;max-width:720px;margin:48px auto;padding:0 20px;color:#2c2926;background:#f7f3ec}h1{font-weight:600}code{background:#f1ebe0;padding:1px 6px;border-radius:5px;font-size:12px}a{color:#c8643c}li{margin:6px 0}</style>
<h1>Design prototype — split by feature</h1>
<p>Static snapshots of <code>08-chat-spine-pro-v7.html</code> (${(src.length / 1024).toFixed(0)}KB, one file). Open any page to point at that feature in isolation.</p>
<ul>
${links}
</ul>`;
writeFileSync(resolve(OUT, "index.html"), indexHtml);

const readme = `# Prototype — split by feature\n\nStatic, per-feature snapshots of \`design/v2-prototypes/08-chat-spine-pro-v7.html\`, generated by \`scripts/split-prototype.mjs\` (Playwright renders each view, then scripts are stripped so the file is a frozen visual reference).\n\nOpen \`index.html\`, or point at one feature:\n\n${done.map((f) => `- **${f.title}** → \`${f.name}.html\``).join("\n")}\n\nRegenerate: \`node scripts/split-prototype.mjs\`. These are read-only references — edit the source prototype, not these.\n`;
writeFileSync(resolve(OUT, "README.md"), readme);

console.log(`\nsaved ${done.length} feature pages + index.html + README.md → ${OUT}`);
