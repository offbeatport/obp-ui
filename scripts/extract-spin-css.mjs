// Extract the spin-flow CSS rules VERBATIM from the design prototype's <style> block and
// scope them under `.cc` (matching src/components/command-center/proto.css). Deterministic —
// copies real declarations so the port is faithful. Load proto.css alongside for the token
// aliases (--paper/--ink/…).  Regenerate, don't hand-edit the output.
//
//   node scripts/extract-spin-css.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const SRC = resolve(root, "design/v2-prototypes/08-chat-spine-pro-v7.html");
const OUT = resolve(root, "src/components/command-center/spin-proto.css");

const html = readFileSync(SRC, "utf8");
// All <style> blocks, comments stripped (so section comments never get mis-scoped).
const css = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/gi)]
    .map((m) => m[1])
    .join("\n")
    .replace(/\/\*[\s\S]*?\*\//g, "");

// Top-level blocks (rule / @media / @keyframes) by brace depth.
function topLevelBlocks(src) {
    const blocks = [];
    let depth = 0;
    let start = 0;
    for (let i = 0; i < src.length; i++) {
        if (src[i] === "{") depth++;
        else if (src[i] === "}") {
            depth--;
            if (depth === 0) {
                blocks.push(src.slice(start, i + 1).trim());
                start = i + 1;
            }
        }
    }
    return blocks.filter(Boolean);
}

// A class token belongs to the spin flow if it EXACTLY equals or is prefixed (`fam-`) by one of
// these. Token-level matching avoids false hits like `.spine-head` (center chat) ⊄ `.spin`.
const FAMILIES = new Set([
    "spin", "spinner", "ql", "host", "exc", "sig", "sp", "sr", "bf", "cc", "cco",
    "co-brandmark", "btn-scout", "btn-primary", "btn-link", "btn-approve", "btn-back",
    "btn-refine", "btn-choose", "rsrc", "rk", "proof", "ctx", "wedge", "dr", "market",
    "signals", "cta", "hdr",
]);
const tokenInFamily = (t) => {
    for (const f of FAMILIES) if (t === f || t.startsWith(`${f}-`)) return true;
    return false;
};
function selectorMatches(sel) {
    const tokens = [...sel.matchAll(/\.([a-zA-Z][\w-]*)/g)].map((m) => m[1]);
    return tokens.some(tokenInFamily);
}

// Prefix each comma-separated selector with `.cc ` (proto.css convention).
const scopeSelector = (sel) =>
    sel
        .split(",")
        .map((s) => s.trim())
        .filter(Boolean)
        .map((s) => `.cc ${s}`)
        .join(",\n");

// Keyframes the spin CSS actually uses (allowlist + anything referenced by a kept rule).
const KEYFRAME_ALLOW = new Set(["spin-rot", "spin-pulse", "spin-blink", "spin-shimmer", "cc-rot"]);

const keep = [];
const included = new Set();
const referencedAnim = new Set();

for (const block of topLevelBlocks(css)) {
    const brace = block.indexOf("{");
    const head = block.slice(0, brace).trim();
    const body = block.slice(brace);

    if (head.startsWith("@keyframes")) continue; // handled in the second pass
    if (head.startsWith("@media")) {
        const inner = topLevelBlocks(body.slice(1, -1))
            .filter((r) => selectorMatches(r.slice(0, r.indexOf("{"))))
            .map((r) => {
                const b = r.indexOf("{");
                return `${scopeSelector(r.slice(0, b))} ${r.slice(b)}`;
            });
        if (inner.length) keep.push(`${head} {\n${inner.join("\n")}\n}`);
        continue;
    }
    if (head.startsWith("@")) continue;

    if (selectorMatches(head)) {
        for (const m of body.matchAll(/animation(?:-name)?\s*:\s*([a-zA-Z0-9_-]+)/g)) {
            referencedAnim.add(m[1]);
        }
        keep.push(`${scopeSelector(head)} ${body}`);
    }
}

// Second pass: include the allowlisted + referenced @keyframes (verbatim, unscoped).
for (const block of topLevelBlocks(css)) {
    const head = block.slice(0, block.indexOf("{")).trim();
    if (!head.startsWith("@keyframes")) continue;
    const name = head.replace("@keyframes", "").trim();
    if ((KEYFRAME_ALLOW.has(name) || referencedAnim.has(name)) && !included.has(name)) {
        keep.push(block);
        included.add(name);
    }
}

const header = `/* ============================================================================
   Spin-flow prototype CSS, ported verbatim from
   design/v2-prototypes/08-chat-spine-pro-v7.html and scoped under \`.cc\` (same
   token aliasing as proto.css — load proto.css alongside for the --paper/--ink/…
   aliases). Generated by scripts/extract-spin-css.mjs; regenerate, don't hand-edit.
   ========================================================================== */
`;
writeFileSync(OUT, header + keep.join("\n\n") + "\n");
console.log(
    `wrote ${keep.length} blocks (${included.size} keyframes: ${[...included].join(", ")}) → ${OUT}`,
);
